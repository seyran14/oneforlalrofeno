/**
 * Достроить составные эмодзи до «полной» формы.
 *
 * Такие эмодзи склеиваются из нескольких через невидимый соединитель ZWJ:
 * «сердце в огне» — это ❤ + ZWJ + 🔥. Но часть символов по умолчанию рисуется
 * как чёрно-белый значок, и чтобы попасть в последовательность, им нужен
 * селектор U+FE0F. Если его потеряли при вводе — а Notion и часть клавиатур
 * его теряют, — система не узнаёт последовательность и показывает два эмодзи
 * вместо одного.
 *
 * Правим только элементы ZWJ-последовательностей: одиночные символы трогать
 * незачем, а список — те, что реально встречаются в составных эмодзи
 * (сердце, глаз, реплика, цепь, профессии, гендерные знаки, стрелка).
 */
const NEEDS_SELECTOR = new Set([
  0x2764, // ❤ сердце: ❤️‍🔥, ❤️‍🩹
  0x1f441, // 👁 глаз: 👁️‍🗨️
  0x1f5e8, // 🗨 реплика
  0x26d3, // ⛓ цепь: ⛓️‍💥
  0x2695, // ⚕ медицина
  0x2696, // ⚖ весы
  0x2708, // ✈ самолёт
  0x2640, // ♀ женский знак
  0x2642, // ♂ мужской знак
  0x26a7, // ⚧ транс-символ
  0x27a1, // ➡ стрелка: 🧑‍➡️
  0x2620, // ☠ череп: 🏴‍☠️
  0x1f576, // 🕶 очки
]);

const ZWJ = 0x200d;
const SELECTOR = 0xfe0f;

export function qualifyEmoji(text: string): string {
  if (!text.includes('‍')) return text;

  const chars = [...text];
  const out: string[] = [];

  for (let i = 0; i < chars.length; i++) {
    const code = chars[i].codePointAt(0)!;
    out.push(chars[i]);

    if (!NEEDS_SELECTOR.has(code)) continue;

    const next = chars[i + 1]?.codePointAt(0);
    const prev = chars[i - 1]?.codePointAt(0);

    // Селектор нужен, только если символ стоит внутри ZWJ-последовательности
    const inSequence = next === ZWJ || prev === ZWJ;
    if (inSequence && next !== SELECTOR) {
      out.push('️');
    }
  }

  return out.join('');
}
